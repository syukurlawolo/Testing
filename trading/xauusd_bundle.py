def _decoded(name: str) -> bytes:
    blob = FILES[name]
    joined = blob if isinstance(blob, str) else "".join(blob)
    return base64.b64decode(joined)


def _sha(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def _self_check() -> list:
    """The bundle must agree with its own recorded hashes."""
    bad = []
    for name, want in EXPECTED.items():
        if name not in FILES:
            bad.append((name, "declared but not embedded"))
        elif _sha(_decoded(name)) != want:
            bad.append((name, "embedded bytes do not match recorded hash"))
    return bad


def cmd_list() -> int:
    print(f"{BUNDLE_ID} v{BUNDLE_VERSION}")
    print(f"target folder: {TARGET_DIR}")
    print()
    print(f"{'file':<26} {'bytes':>9}  {'state':<10} sha256")
    print("-" * 78)
    for name in EXPECTED:
        raw = _decoded(name)
        p = TARGET_DIR / name
        if not p.exists():
            state = "ABSENT"
        elif _sha(p.read_bytes()) == EXPECTED[name]:
            state = "match"
        else:
            state = "DRIFT"
        print(f"{name:<26} {len(raw):>9,}  {state:<10} {EXPECTED[name][:16]}...")
    return 0


def cmd_verify(verbose: bool = True) -> int:
    bad = _self_check()
    if bad:
        print("BUNDLE IS CORRUPT:")
        for name, why in bad:
            print(f"  {name}: {why}")
        return 4

    drift, absent = [], []
    for name, want in EXPECTED.items():
        p = TARGET_DIR / name
        if not p.exists():
            absent.append(name)
        elif _sha(p.read_bytes()) != want and name not in STATE_FILES:
            drift.append(name)

    if verbose:
        print(f"{BUNDLE_ID} v{BUNDLE_VERSION}")
        print(f"checking {TARGET_DIR}")
        print()
        for name in EXPECTED:
            p = TARGET_DIR / name
            if not p.exists():
                mark = "ABSENT"
            elif name in drift:
                mark = "DRIFT"
            elif name in STATE_FILES and p.exists() and _sha(p.read_bytes()) != EXPECTED[name]:
                mark = "live"
            else:
                mark = "ok"
            print(f"  {mark:<8} {name}")

    if absent or drift:
        print()
        if drift:
            print(f"DRIFT: {len(drift)} file(s) differ from the frozen copy")
            print("  " + ", ".join(drift))
        if absent:
            print(f"MISSING: {len(absent)} file(s) not on disk")
            print("  " + ", ".join(absent))
        print()
        print("To put the frozen bytes back:  python xauusd_bundle.py --restore")
        return 3 if absent else 2

    if verbose:
        print()
        print("OK - every file matches the frozen copy.")
    return 0


def cmd_diff() -> int:
    bad = _self_check()
    if bad:
        print("BUNDLE IS CORRUPT:", bad)
        return 4
    any_diff = False
    for name, want in EXPECTED.items():
        p = TARGET_DIR / name
        if not p.exists():
            print(f"{name}: ABSENT on disk")
            any_diff = True
        elif _sha(p.read_bytes()) != want:
            print(f"{name}: DRIFT (disk {_sha(p.read_bytes())} != frozen {want})")
            any_diff = True
    if not any_diff:
        print("No differences.")
    return 0


def cmd_restore(force: bool) -> int:
    bad = _self_check()
    if bad:
        print("REFUSING TO RESTORE - the bundle itself is corrupt:")
        for name, why in bad:
            print(f"  {name}: {why}")
        return 4

    TARGET_DIR.mkdir(parents=True, exist_ok=True)
    written, skipped, kept = [], [], []
    for name, want in EXPECTED.items():
        p = TARGET_DIR / name
        raw = _decoded(name)

        # Runtime memory is never overwritten. If it is already there, it is the
        # truth; restoring the older snapshot would make the bot re-send signals.
        if name in STATE_FILES and p.exists():
            kept.append(name)
            print(f"  kept {name:<30} (live state preserved)")
            continue

        if p.exists() and _sha(p.read_bytes()) == want:
            skipped.append(name)
            continue
        if p.exists() and not force:
            print(f"  ! {name} exists and differs - restoring over it anyway "
                  f"(use --force to silence this note)")
        p.write_bytes(raw)
        written.append(name)
        print(f"  restored {name:<30} {len(raw):>7,} B")

    print()
    print(f"restore complete: {len(written)} written, {len(skipped)} already correct"
          + (f", {len(kept)} live state kept" if kept else ""))
    if written:
        print()
        print("NEXT STEPS")
        print("  1. Check the locked methods still self-verify:")
        print("       python xauusd_method_LOCKED_H4.py --verify")
        print("       python xauusd_method_LOCKED.py --verify")
        print("  2. Re-register the Windows scheduled tasks:")
        print("       register_tasks.bat")
        print("  3. Make sure tg.json still holds the bot token + chat id.")
        print("  4. Health check:  CEK_STATUS.bat")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description="Frozen bundle of the XAUUSD locked method signal robot.")
    ap.add_argument("--verify", action="store_true",
                    help="compare files on disk against the frozen copy")
    ap.add_argument("--restore", action="store_true",
                    help="write the frozen files back to the target folder")
    ap.add_argument("--list", action="store_true", help="show contents and hashes")
    ap.add_argument("--diff", action="store_true", help="show only differences")
    ap.add_argument("--force", action="store_true",
                    help="with --restore, do not warn about overwrites")
    args = ap.parse_args(argv)

    if args.restore:
        return cmd_restore(args.force)
    if args.list:
        return cmd_list()
    if args.diff:
        return cmd_diff()
    # Default action is verify - safest.
    return cmd_verify()


if __name__ == "__main__":
    raise SystemExit(main())
